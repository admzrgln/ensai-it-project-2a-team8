
-- Movies

CREATE TABLE IF NOT EXISTS public.movie (
    id_movie INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    duration INTEGER NOT NULL CHECK (duration > 0),
    genre VARCHAR(100) NOT NULL,
    external_id VARCHAR(100) NOT NULL,
    poster_url TEXT NOT NULL,

    CONSTRAINT valid_genre
        CHECK (genre IN (
            'Action',
            'Comédie',
            'Drame',
            'Science-fiction',
            'Horreur'
        ))
);


-- Rooms

CREATE TABLE IF NOT EXISTS public.room (
    id_room INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(50) NOT NULL,
    number INTEGER NOT NULL UNIQUE,
    capacity INTEGER NOT NULL CHECK (capacity > 0)
);


-- Users

CREATE TABLE IF NOT EXISTS public.app_user (
    id_user INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password TEXT NOT NULL,
    date_of_birth DATE,
    role VARCHAR(20) NOT NULL
        CHECK (role IN ('admin', 'customer')),
    is_ensai_student BOOLEAN NOT NULL DEFAULT FALSE
);


-- Screenings

CREATE TABLE IF NOT EXISTS public.screening (
    id_screening INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_room INTEGER NOT NULL,
    id_movie INTEGER NOT NULL,
    id_admin INTEGER NOT NULL,

    date_time TIMESTAMP NOT NULL,
    base_price NUMERIC(8,2) NOT NULL CHECK (base_price >= 0),
    available_seats INTEGER NOT NULL CHECK (available_seats >= 0),

    CONSTRAINT fk_screening_room
        FOREIGN KEY (id_room)
        REFERENCES public.room(id_room),

    CONSTRAINT fk_screening_movie
        FOREIGN KEY (id_movie)
        REFERENCES public.movie(id_movie),

    CONSTRAINT fk_screening_admin
        FOREIGN KEY (id_admin)
        REFERENCES public.app_user(id_user)
);
