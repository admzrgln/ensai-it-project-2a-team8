
-- Ensai Cinema Club - database schema (PostgreSQL)

CREATE TABLE IF NOT EXISTS public.movie (
    id_movie INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    duration INTEGER NOT NULL CHECK (duration > 0), 
    genre VARCHAR(100) NOT NULL,                     
    external_id VARCHAR(100) NOT NULL,               
    poster_url TEXT NOT NULL,

    CONSTRAINT valid_genre
        CHECK (genre IN (
            'Action', 'Adventure', 'Animation', 'Biography', 'Comedy', 'Crime',
            'Documentary', 'Drama', 'Family', 'Fantasy', 'Film-Noir', 'History',
            'Horror', 'Music', 'Musical', 'Mystery', 'Romance', 'Sci-Fi',
            'Science-fiction', 'Sport', 'Thriller', 'War', 'Western'
        ))
);


CREATE TABLE IF NOT EXISTS public.room (
    id_room INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number INTEGER NOT NULL UNIQUE,
    capacity INTEGER NOT NULL CHECK (capacity > 0)
);


CREATE TABLE IF NOT EXISTS public.app_user (
    id_user INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password TEXT NOT NULL,
    salt TEXT,
    date_of_birth DATE,
    role VARCHAR(20) NOT NULL
        CHECK (role IN ('admin', 'customer')),
    is_ensai_student BOOLEAN NOT NULL DEFAULT FALSE
);


CREATE TABLE IF NOT EXISTS public.screening (
    id_screening INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_room INTEGER NOT NULL,
    id_movie INTEGER NOT NULL,
    id_admin INTEGER NOT NULL,

    date_time TIMESTAMP NOT NULL,
    available_seats INTEGER NOT NULL CHECK (available_seats >= 0),

    CONSTRAINT fk_screening_room
        FOREIGN KEY (id_room)
        REFERENCES public.room(id_room),

    CONSTRAINT fk_screening_movie
        FOREIGN KEY (id_movie)
        REFERENCES public.movie(id_movie),

    CONSTRAINT fk_screening_admin
        FOREIGN KEY (id_admin)
        REFERENCES public.app_user(id_user)
);


CREATE TABLE IF NOT EXISTS public.tariff (
    code VARCHAR(30) PRIMARY KEY,
    label VARCHAR(100) NOT NULL,
    price NUMERIC(8,2) NOT NULL CHECK (price IS NULL OR price >= 0),
    min_age INTEGER CHECK (min_age IS NULL OR min_age >= 0),
    max_age INTEGER CHECK (max_age IS NULL OR max_age >= 0),
    requires_ensai BOOLEAN NOT NULL DEFAULT FALSE,
    requires_student BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    weekday SMALLINT CHECK (weekday >= 0 AND weekday <= 6),
    time_from TIME,
    time_until TIME,

    CONSTRAINT valid_age_range
        CHECK (min_age IS NULL OR max_age IS NULL OR min_age <= max_age)
);


CREATE TABLE IF NOT EXISTS public.price_revision (
    year INTEGER PRIMARY KEY CHECK (year >= 2026),
    rate_percent NUMERIC(4,2) NOT NULL CHECK (rate_percent >= 0 AND rate_percent <= 10),  -- in %
    applied_at TIMESTAMP
);


CREATE TABLE IF NOT EXISTS public.booking (
    id_booking INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_customer INTEGER NOT NULL,
    id_screening INTEGER NOT NULL,
    booking_date TIMESTAMP NOT NULL DEFAULT now(),
    status VARCHAR(20) NOT NULL DEFAULT 'confirmed'
        CHECK (status IN ('confirmed', 'cancelled')),
    seat_count INTEGER NOT NULL CHECK (seat_count > 0),
    total_price NUMERIC(8,2) NOT NULL CHECK (total_price >= 0),

    CONSTRAINT fk_booking_customer
        FOREIGN KEY (id_customer)
        REFERENCES public.app_user(id_user),

    CONSTRAINT fk_booking_screening
        FOREIGN KEY (id_screening)
        REFERENCES public.screening(id_screening)
);


CREATE TABLE IF NOT EXISTS public.ticket (
    id_ticket INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_booking INTEGER NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    date_of_birth DATE NOT NULL,
    is_holder BOOLEAN NOT NULL DEFAULT FALSE, 
    is_ensai_student BOOLEAN NOT NULL DEFAULT FALSE,
    is_student BOOLEAN NOT NULL DEFAULT FALSE,
    tariff_code VARCHAR(30) NOT NULL,
    price NUMERIC(8,2) NOT NULL CHECK (price >= 0),

    CONSTRAINT fk_ticket_booking
        FOREIGN KEY (id_booking)
        REFERENCES public.booking(id_booking)
        ON DELETE CASCADE,

    CONSTRAINT fk_ticket_tariff
        FOREIGN KEY (tariff_code)
        REFERENCES public.tariff(code)
);


CREATE INDEX IF NOT EXISTS idx_screening_date ON public.screening(date_time);
CREATE INDEX IF NOT EXISTS idx_booking_customer ON public.booking(id_customer);
CREATE INDEX IF NOT EXISTS idx_booking_screening ON public.booking(id_screening);
CREATE INDEX IF NOT EXISTS idx_booking_date ON public.booking(booking_date);
CREATE INDEX IF NOT EXISTS idx_ticket_booking ON public.ticket(id_booking);