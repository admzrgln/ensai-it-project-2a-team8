import logging
from datetime import datetime
from typing import Any

from fastapi import APIRouter, HTTPException
from pydantic import BaseModel

from backend.src.Controller.JWTBearer import AdminPayload
from backend.src.Model.Screening import Screening
from backend.src.Service.MovieService import MovieService
from backend.src.Service.ScreeningService import ScreeningError, ScreeningNotFoundError, ScreeningService

screening_router = APIRouter(prefix="/screenings")
screening_service = ScreeningService()
movie_service = MovieService()


class ScreeningModel(BaseModel):
    """Body of the requests creating or updating a screening.

    No identifier (generated by the database, or read in the URL), no administrator (read in
    the token) and no number of seats (computed from the room and the bookings).
    """

    id_room: int
    id_movie: int
    date_time: datetime


@screening_router.get("/", tags=["Screenings"], response_model=None)
async def find_all_screenings() -> list[dict[str, Any]]:
    """List all the screenings, with the title of their movie.

    Returns
    -------
    list of dict
        The screenings, by date.
    """
    logging.info("List all screenings")
    screenings_list = screening_service.find_all()
    enriched_screenings = []
    for screening in screenings_list:
        movie = movie_service.find_by_id(screening.id_movie)
        screening_dict = screening.__dict__.copy()
        screening_dict["movie_title"] = movie.title if movie else "Film inconnu"
        enriched_screenings.append(screening_dict)

    return enriched_screenings


@screening_router.get("/movie/{id_movie}", tags=["Screenings"], response_model=None)
async def screenings_by_movie(id_movie: int) -> list[Screening]:
    """List the screenings of a movie.

    Parameters
    ----------
    id_movie : int
        Identifier of the movie.

    Returns
    -------
    list of Screening
        The screenings of the movie, by date.
    """
    logging.info(f"Find screenings of movie: {id_movie}")
    return screening_service.find_by_movie(id_movie)


@screening_router.get("/{id_screening}", tags=["Screenings"], response_model=None)
async def screening_by_id(id_screening: int) -> Screening:
    """Find a screening by its identifier.

    Parameters
    ----------
    id_screening : int
        Identifier of the screening.

    Returns
    -------
    Screening
        The screening (error 404 if it does not exist).
    """
    logging.info(f"Find a screening by id: {id_screening}")
    screening = screening_service.find_by_id(id_screening)
    if not screening:
        raise HTTPException(status_code=404, detail="Screening not found")
    return screening


@screening_router.post("/", tags=["Screenings"], status_code=201, response_model=None)
async def create_screening(data: ScreeningModel, admin: AdminPayload) -> Screening:
    """Create a new screening (administrators only).

    Parameters
    ----------
    data : ScreeningModel
        Room, movie and start of the screening.
    admin : dict
        Token of the logged-in administrator, who becomes the planner.

    Returns
    -------
    Screening
        The screening created (error 400 with the reason if a rule is not respected).
    """
    logging.info(f"Admin {admin['user_id']} creates a screening for movie {data.id_movie}")
    new_screening = Screening(
        id_screening=None,
        id_room=data.id_room,
        id_movie=data.id_movie,
        id_admin=admin["user_id"],
        date_time=data.date_time,
    )
    try:
        screening_service.create_screening(new_screening)
    except ScreeningError as e:
        raise HTTPException(status_code=400, detail=str(e)) from e
    return new_screening


@screening_router.put("/{id_screening}", tags=["Screenings"], response_model=None)
async def update_screening(id_screening: int, data: ScreeningModel, admin: AdminPayload) -> dict[str, Any]:
    """Update a screening (administrators only); the administrator becomes its planner.

    Parameters
    ----------
    id_screening : int
        Identifier of the screening.
    data : ScreeningModel
        New room, movie and start of the screening.
    admin : dict
        Token of the logged-in administrator.

    Returns
    -------
    dict
        Confirmation message and the screening
        (error 404 if it does not exist, 400 if a rule is not respected).
    """
    logging.info(f"Admin {admin['user_id']} updates screening id: {id_screening}")
    updated = Screening(
        id_screening=id_screening,
        id_room=data.id_room,
        id_movie=data.id_movie,
        id_admin=admin["user_id"],
        date_time=data.date_time,
    )
    try:
        screening_service.update_screening(updated)
    except ScreeningNotFoundError as e:
        raise HTTPException(status_code=404, detail=str(e)) from e
    except ScreeningError as e:
        raise HTTPException(status_code=400, detail=str(e)) from e
    return {"message": "Screening updated successfully", "screening": updated}


@screening_router.delete("/{id_screening}", tags=["Screenings"], response_model=None)
async def delete_screening(id_screening: int, admin: AdminPayload) -> dict[str, str]:
    """Delete a screening (administrators only).

    Parameters
    ----------
    id_screening : int
        Identifier of the screening.
    admin : dict
        Token of the logged-in administrator.

    Returns
    -------
    dict
        Confirmation message (error 404 if the screening does not exist).
    """
    logging.info(f"Admin {admin['user_id']} deletes screening id: {id_screening}")
    if not screening_service.delete_screening(id_screening):
        raise HTTPException(status_code=404, detail="Screening not found")
    return {"message": f"Screening {id_screening} deleted successfully"}
